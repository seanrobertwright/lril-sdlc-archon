/**
 * Matt Pocock's /triage state machine: every triaged issue carries exactly one
 * category role and one state role, every comment starts with the AI disclaimer,
 * and each outcome has the shape its role demands (an agent brief, triage notes,
 * or a close with its reason).
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { CATEGORIES, ROLES, type Category, type Role } from './tracker.ts';

export const DISCLAIMER = '> *This was generated by AI during triage.*';

export interface Outcome {
  readonly category: Category;
  readonly state: Role;
  readonly comment: string;
  readonly close: boolean;
  readonly wontfix_reason: '' | 'already-implemented' | 'rejected';
  readonly out_of_scope: { readonly file: string; readonly content: string } | null;
}

const BRIEF_FIELDS = [
  '## Agent Brief',
  '**Category:**',
  '**Summary:**',
  '**Current behavior:**',
  '**Desired behavior:**',
  '**Key interfaces:**',
  '**Acceptance criteria:**',
  '**Out of scope:**',
];

const NOTES_FIELDS = ['## Triage Notes', "**What we've established so far:**", '**What we still need from you'];

export function outcomeProblems(value: unknown): string[] {
  if (typeof value !== 'object' || value === null) return ['outcome.json is not an object'];
  const outcome = value as Record<string, unknown>;
  const problems: string[] = [];
  const category = outcome.category;
  const state = outcome.state;
  const comment = typeof outcome.comment === 'string' ? outcome.comment.trim() : undefined;
  if (!(CATEGORIES as readonly unknown[]).includes(category)) problems.push(`category must be one of ${CATEGORIES.join(', ')}`);
  if (!(ROLES as readonly unknown[]).includes(state)) problems.push(`state must be one of ${ROLES.join(', ')}`);
  if (comment === undefined) problems.push('comment must be a string');
  if (typeof outcome.close !== 'boolean') problems.push('close must be a boolean');
  if (!['', 'already-implemented', 'rejected'].includes(outcome.wontfix_reason as string)) {
    problems.push('wontfix_reason must be "", "already-implemented" or "rejected"');
  }
  const oos = outcome.out_of_scope;
  const oosRecord = typeof oos === 'object' && oos !== null ? (oos as Record<string, unknown>) : undefined;
  const oosValid =
    oos === null ||
    (oosRecord !== undefined &&
      typeof oosRecord.file === 'string' &&
      /^[a-z0-9][a-z0-9-]*\.md$/.test(oosRecord.file) &&
      typeof oosRecord.content === 'string');
  if (!oosValid) problems.push('out_of_scope must be null or { file: "<kebab-concept>.md", content: "<markdown>" }');
  if (problems.length > 0 || comment === undefined) return problems;

  if (comment !== '' && !comment.startsWith(DISCLAIMER)) problems.push(`the comment must start with: ${DISCLAIMER}`);
  if (comment === '' && state !== 'needs-triage') problems.push(`a ${String(state)} outcome needs a comment`);
  if (state === 'ready-for-agent' || state === 'ready-for-human') {
    for (const field of BRIEF_FIELDS) if (!comment.includes(field)) problems.push(`the agent brief is missing "${field}"`);
    if (!/^\s*- \[ \]/m.test(comment)) problems.push('the agent brief needs testable "- [ ]" acceptance criteria');
  }
  if (state === 'needs-info') {
    for (const field of NOTES_FIELDS) if (!comment.includes(field)) problems.push(`the triage notes are missing "${field}"`);
  }
  if (state === 'wontfix') {
    if (outcome.close !== true) problems.push('a wontfix outcome closes the issue (close: true)');
    if (outcome.wontfix_reason === '') problems.push('a wontfix outcome names its reason');
    const rejectedEnhancement = category === 'enhancement' && outcome.wontfix_reason === 'rejected';
    if (rejectedEnhancement && oos === null) problems.push('a rejected enhancement is recorded in .out-of-scope/ (out_of_scope)');
    if (!rejectedEnhancement && oos !== null) {
      problems.push('only a rejected enhancement writes .out-of-scope/ (never an already-implemented one, never a bug)');
    }
  } else {
    if (outcome.close === true) problems.push(`a ${String(state)} outcome does not close the issue`);
    if (oos !== null) problems.push('only a rejected enhancement writes .out-of-scope/');
    if (outcome.wontfix_reason !== '') problems.push('wontfix_reason is only for wontfix');
  }
  return problems;
}

export function readOutcome(artifacts: string): { outcome: Outcome | undefined; problems: string[] } {
  const path = join(artifacts, 'triage', 'outcome.json');
  if (!existsSync(path)) return { outcome: undefined, problems: ['triage/outcome.json is missing'] };
  let parsed: unknown;
  try {
    parsed = JSON.parse(readFileSync(path, 'utf8'));
  } catch {
    return { outcome: undefined, problems: ['triage/outcome.json is not valid JSON'] };
  }
  const problems = outcomeProblems(parsed);
  return { outcome: problems.length === 0 ? (parsed as Outcome) : undefined, problems };
}
